/* 1 - Quantos carros cada cliente tem? */
SELECT
    CLIENTES.NOME,
    COUNT(VEICULOS.ID) AS "QTD_CARROS"
FROM CLIENTES
INNER JOIN VEICULOS
ON CLIENTES.ID = VEICULOS.FK_CLIENTES_ID
GROUP BY CLIENTES.ID, CLIENTES.NOME;

/* 2 - Quantos agendamentos cada veículo tem? */
SELECT
	VEICULOS.ID,
    VEICULOS.PLACA,
    VEICULOS.MODELO,
    VEICULOS.MARCA,
    COUNT(AGENDAMENTOS.ID) AS "QTD_AGENDAMENTOS"
FROM VEICULOS
INNER JOIN AGENDAMENTOS
ON VEICULOS.ID = AGENDAMENTOS.FK_VEICULO_ID
GROUP BY VEICULOS.ID, VEICULOS.PLACA, VEICULOS.MODELO;

/* 3 - Quantos agendamentos cada CLIENTE tem? */
SELECT CLIENTES.NOME AS "NOME DO CLIENTE",
      COUNT(AGENDAMENTOS.ID) AS "TOTAL DE AGENDAMENTOS"
FROM CLIENTES
LEFT JOIN VEICULOS
ON CLIENTES.ID = VEICULOS.FK_CLIENTES_ID
LEFT JOIN AGENDAMENTOS
ON VEICULOS.ID = AGENDAMENTOS.FK_VEICULO_ID
GROUP BY CLIENTES.ID, CLIENTES.NOME;