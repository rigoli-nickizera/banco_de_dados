CREATE DATABASE IF NOT EXISTS BD_OFICINA_MECANICA;
USE BD_OFICINA_MECANICA;

CREATE TABLE IF NOT EXISTS CLIENTES(
ID INT AUTO_INCREMENT PRIMARY KEY ,
	NOME VARCHAR(100) NOT NULL,
    CPF VARCHAR(255) NOT NULL,
    TELEFONE VARCHAR(20) ,
    EMAIL VARCHAR(100) ,
     CREATED_AT TIMESTAMP NULL,
    UPDATED_AT TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS VEICULOS(
ID  INT  AUTO_INCREMENT PRIMARY KEY,
    PLACA VARCHAR(100) NOT NULL,
    MARCA VARCHAR(50) NOT NULL,
    MODELO VARCHAR(50),
    FK_CLIENTES_ID INT NOT NULL,
    FOREIGN KEY (FK_CLIENTES_ID) REFERENCES CLIENTES(ID),
    CREATED_AT TIMESTAMP NULL,
    UPDATED_AT TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS AGENDAMENTOS(
ID INT AUTO_INCREMENT PRIMARY KEY,
    DATAA DATE NOT NULL,
    HORA TIME NOT NULL,
    DESCRICAO VARCHAR(255) ,
    FK_VEICULO_ID INT NOT NULL,
    FOREIGN KEY (FK_VEICULO_ID) REFERENCES VEICULOS(ID),
    CREATED_AT TIMESTAMP NULL,
    UPDATED_AT TIMESTAMP NULL
);

